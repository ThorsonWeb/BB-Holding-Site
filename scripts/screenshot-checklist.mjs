// Writes SCREENSHOTS.md from src/content/screenshots.json and marks which files are already in public/screenshots.
// Run with `npm run screenshots` after adding or changing a slot, or after dropping new images in.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const data = JSON.parse(fs.readFileSync(path.join(root, "src/content/screenshots.json"), "utf8"));
const EXTENSIONS = ["png", "jpg", "jpeg", "webp"];

function found(product, id) {
  return EXTENSIONS.map((ext) => `public/screenshots/${product}/${id}.${ext}`).find((rel) =>
    fs.existsSync(path.join(root, rel))
  );
}

function section(product, heading, intro) {
  const rows = data[product].map((shot) => {
    const file = found(product, shot.id);
    const status = file ? "Done" : shot.fallback ? "Needed (old image showing)" : "Needed";
    return `| ${status} | \`${product}/${shot.id}.png\` | ${shot.title} | ${shot.usedOn.join("<br>")} | ${shot.capture} |`;
  });
  const missing = data[product].filter((shot) => !found(product, shot.id)).length;
  return [
    `## ${heading}`,
    "",
    intro,
    "",
    `${data[product].length - missing} of ${data[product].length} done.`,
    "",
    "| Status | File | Screen | Where it appears | What to capture |",
    "|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

const md = [
  "# Screenshot checklist",
  "",
  "Generated by `npm run screenshots` from `src/content/screenshots.json`. Don't edit this file by hand.",
  "",
  "Save each image under `public/screenshots/` with the exact file name below (`.png`, `.jpg` or `.webp` all work), then rebuild.",
  "Until a file exists the site shows a placeholder labelled with the screen name in that spot.",
  "",
  section(
    "app",
    "Battle Beacon app",
    "Portrait phone screenshots, about 1080 × 2340 (any modern phone's native size is fine). Use a clean status bar, test data only (no real names, emails or postcodes), and the same theme across all shots."
  ),
  section(
    "crm",
    "NorthMark CRM",
    "Landscape desktop screenshots, 1600 px wide. These are copied from the NorthMark CRM repo (`Beacon-CRM/wwwroot/img/site`). Recopy them when those images change."
  ),
].join("\n");

fs.writeFileSync(path.join(root, "SCREENSHOTS.md"), md);
const total = data.app.length + data.crm.length;
const missing = [...data.app.map((s) => ["app", s]), ...data.crm.map((s) => ["crm", s])].filter(
  ([product, s]) => !found(product, s.id)
);
console.log(`SCREENSHOTS.md written. ${total - missing.length}/${total} screenshots in place.`);
for (const [product, s] of missing) console.log(`  missing: public/screenshots/${product}/${s.id}.png`);
